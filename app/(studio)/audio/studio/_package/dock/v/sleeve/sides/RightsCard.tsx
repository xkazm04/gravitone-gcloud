"use client";

// One track's AI & rights card (side A3): DistroKid's AI credits (which parts were generated; with all the audio, whether
// the artist is a human or an AI persona) and the provenance record the take was accepted with - fully in this
// direction's design. Rights warn and stop nothing (owner, wave 2); the persona, unstated over all-AI audio, blocks.
import { Button } from "@gt/ui/components/button/Button.tsx";
import { Field } from "@gt/ui/components/field/Field.tsx";
import { Seg } from "@gt/ui/components/seg/Seg.tsx";
import { Toggle } from "@gt/ui/components/toggle/Toggle.tsx";
import { AI_AUDIO, LICENCES, type AiCredits, type RightsRecord } from "@gt/domain/release";

import { pendingIn } from "../../../../../../_release/pending.ts";
import { orNull } from "../../../../../../_release/wizard/fmt.ts";
import { problemsOnTrack } from "../../../../../../_release/wizard/steps.ts";
import type { SideProps } from "../liner.ts";
import { Margin } from "../Margin.tsx";
import { Errata } from "../Print.tsx";
import { FormCell, FormRule, PrintedCard } from "../PrintedCard.tsx";
import c from "../card.module.css";
import { LICENCE_LABEL, RECORD_FIELDS } from "./rights.ts";

type PersonaChoice = "human" | "ai" | "unstated";

export function RightsCard({ index, onClose, side }: { readonly index: number | null; readonly onClose: () => void; readonly side: SideProps }) {
  const { release: r, problems, dispatch, session } = side;
  const t = index === null ? undefined : r.tracks[index];
  const i = index ?? 0;
  const patchAi = (f: Partial<AiCredits>) => t !== undefined && dispatch({ type: "patchTrack", id: r.id, index: i, fields: { ai: { ...t.ai, ...f } } });
  const patchRights = (f: Partial<RightsRecord>) => t !== undefined && dispatch({ type: "patchTrack", id: r.id, index: i, fields: { rights: { ...t.rights, ...f } } });
  const copyToAll = () => t !== undefined && r.tracks.forEach((_, j) => j !== i && dispatch({ type: "patchTrack", id: r.id, index: j, fields: { ai: t.ai, rights: t.rights } }));
  const notes = pendingIn(session.pending, "rights").filter((p) => p.path.startsWith(`track:${i + 1}.`));
  return (
    <PrintedCard
      open={t !== undefined}
      onClose={onClose}
      title={t === undefined || t.title.trim() === "" ? `track ${i + 1}` : t.title}
      mark={`A3 · AI & rights · track ${i + 1}`}
      wide
      foot={
        <span className={c.acts}>
          {r.tracks.length > 1 && <Button label={`Copy to all ${r.tracks.length} tracks`} size="sm" onPress={copyToAll} />}
          <Button label="Done" size="sm" tone="cyan" onPress={onClose} />
        </span>
      }
    >
      {t !== undefined && (
        <>
          <FormRule title="AI credits">
            <FormCell term="lyrics">
              <Toggle label={t.ai.lyrics ? "AI-written" : "human-written"} on={t.ai.lyrics} onToggle={(v) => patchAi({ lyrics: v })} name="lyrics generated by AI" />
            </FormCell>
            <FormCell term="music">
              <Toggle label={t.ai.music ? "AI-composed" : "human-composed"} on={t.ai.music} onToggle={(v) => patchAi({ music: v })} name="music generated by AI" />
            </FormCell>
            <FormCell term="audio">
              <Seg label="audio generated by AI" options={AI_AUDIO.map((a) => ({ value: a, label: a }))} value={t.ai.audio} onChange={(v) => patchAi({ audio: v, persona: v === "all" ? t.ai.persona : null })} />
            </FormCell>
            {t.ai.audio === "all" && (
              <FormCell term="artist is" w="wide">
                <Seg<PersonaChoice>
                  label="the artist is a human or an AI persona"
                  options={[
                    { value: "human", label: "a human" },
                    { value: "ai", label: "an AI persona" },
                    { value: "unstated", label: "unstated" },
                  ]}
                  value={t.ai.persona ?? "unstated"}
                  onChange={(v) => patchAi({ persona: v === "unstated" ? null : v })}
                />
              </FormCell>
            )}
          </FormRule>
          <FormRule title="rights record">
            {RECORD_FIELDS.map((f) => (
              <FormCell key={f.key} term={f.label}>
                <Field label={f.label} value={t.rights[f.key] ?? ""} placeholder={f.example} onChange={(v) => patchRights({ [f.key]: orNull(v) })} />
              </FormCell>
            ))}
            <FormCell term="licence" w="wide">
              <Seg label="licence" options={LICENCES.map((l) => ({ value: l, label: LICENCE_LABEL[l] }))} value={t.rights.licence} onChange={(v) => patchRights({ licence: v })} />
            </FormCell>
          </FormRule>
          <Margin notes={notes} session={session} side={`track ${i + 1} rights`} />
          <Errata problems={problemsOnTrack(problems, "rights", i)} label={`track ${i + 1} problems`} />
        </>
      )}
    </PrintedCard>
  );
}
