"use client";

// AI & RIGHTS ON THE CARD, per track: the AI credits as four switches (lyrics, music, audio, and - when all the audio
// was generated - who the artist is, the one a store insists on), and the rights record as a seal: its licence large,
// generator, model and plan tier as chips, a missing one as a quiet gap. The full record opens in a dialog.
import { motion, useReducedMotion } from "motion/react";
import type { ReactNode } from "react";

import { Button } from "@gt/ui/components/button/Button.tsx";
import { Chip } from "@gt/ui/components/chip/Chip.tsx";
import { Seg } from "@gt/ui/components/seg/Seg.tsx";
import { Toggle } from "@gt/ui/components/toggle/Toggle.tsx";
import { AI_AUDIO, type AiCredits, type ReleaseTrack, type RightsRecord } from "@gt/domain/release";
import { rightsWarnings } from "@gt/domain/release.problems";

import type { StepProps } from "../../../../../../_release/wizard/steps.ts";
import { SETTLE } from "../motion.ts";
import { RecordDoor } from "./Record.tsx";
import { TrackPicker } from "./TrackPicker.tsx";
import s from "./steps.module.css";

type PersonaChoice = "human" | "ai" | "unstated";
const LICENCE_WORD = { commercial: "commercial", "cc-by-nc": "CC BY-NC", unknown: "unknown" } as const;
const LICENCE_TONE = { commercial: "ok", "cc-by-nc": "block", unknown: "warn" } as const;

function Switch({ label, need = false, children }: { readonly label: string; readonly need?: boolean; readonly children: ReactNode }) {
  return (
    <div className={s.switch} data-need={need ? "" : undefined}>
      <span className={s.k}>{label}</span>
      {children}
    </div>
  );
}

function AiCreditsPanel({ t, patch }: { readonly t: ReleaseTrack; readonly patch: (f: Partial<AiCredits>) => void }) {
  const persona: PersonaChoice = t.ai.persona ?? "unstated";
  return (
    <section className={s.panel} aria-label="AI credits">
      <span className={s.panelHead}>AI credits</span>
      <div className={s.switches}>
        <Switch label="lyrics">
          <Toggle label={t.ai.lyrics ? "AI-written" : "human-written"} on={t.ai.lyrics} onToggle={(v) => patch({ lyrics: v })} name="lyrics generated by AI" />
        </Switch>
        <Switch label="music">
          <Toggle label={t.ai.music ? "AI-composed" : "human-composed"} on={t.ai.music} onToggle={(v) => patch({ music: v })} name="music generated by AI" />
        </Switch>
        <Switch label="audio">
          <Seg label="audio generated by AI" options={AI_AUDIO.map((a) => ({ value: a, label: a }))} value={t.ai.audio} onChange={(v) => patch({ audio: v, persona: v === "all" ? t.ai.persona : null })} />
        </Switch>
        {t.ai.audio === "all" && (
          <Switch label="artist is" need={t.ai.persona === null}>
            <Seg<PersonaChoice>
              label="the artist is a human or an AI persona"
              options={[
                { value: "human", label: "a human", glyph: "operator" },
                { value: "ai", label: "an AI persona", glyph: "agent" },
                { value: "unstated", label: "unstated" },
              ]}
              value={persona}
              onChange={(v) => patch({ persona: v === "unstated" ? null : v })}
            />
          </Switch>
        )}
      </div>
    </section>
  );
}

function RightsSeal({ t, i, patch }: { readonly t: ReleaseTrack; readonly i: number; readonly patch: (f: Partial<RightsRecord>) => void }) {
  const reduce = useReducedMotion() === true;
  const rec = t.rights;
  const gaps = rightsWarnings(rec).length;
  const chip = (label: string, v: string | null) => (v === null ? <Chip label={`${label} ?`} casing="lower" ghost name={`${label} unknown`} /> : <Chip label={label} value={v} casing="lower" />);
  return (
    <section className={s.panel} aria-label="rights record">
      <span className={s.panelHead}>
        rights record
        <RecordDoor t={t} i={i} patch={patch} />
      </span>
      <motion.span key={rec.licence} className={s.seal} data-tone={LICENCE_TONE[rec.licence]} initial={reduce ? false : { scale: 0.92, opacity: 0 }} animate={{ scale: 1, opacity: 1 }} transition={SETTLE}>
        <span className={s.sealLabel}>licence</span>
        <span className={s.sealValue}>{LICENCE_WORD[rec.licence]}</span>
      </motion.span>
      <span className={s.sealChips}>
        {chip("generator", rec.vendor)}
        {chip("model", rec.model)}
        {chip("tier", rec.planTier)}
        {chip("generated", rec.generatedAt)}
      </span>
      {gaps === 0 && <Chip label="record complete" tone="emerald" dot />}
    </section>
  );
}

export function RightsBody(props: StepProps) {
  const { release: r, problems, dispatch, track, setTrack, session } = props;
  const t = r.tracks[track];
  if (t === undefined) return <Chip label="no tracks" ghost />;
  const patchAi = (f: Partial<AiCredits>) => dispatch({ type: "patchTrack", id: r.id, index: track, fields: { ai: { ...t.ai, ...f } } });
  const patchRights = (f: Partial<RightsRecord>) => dispatch({ type: "patchTrack", id: r.id, index: track, fields: { rights: { ...t.rights, ...f } } });
  const copyToAll = () => r.tracks.forEach((_, i) => i !== track && dispatch({ type: "patchTrack", id: r.id, index: i, fields: { ai: t.ai, rights: t.rights } }));
  return (
    <div className={s.body}>
      {r.tracks.length > 1 && (
        <div className={s.toolbar}>
          <TrackPicker tracks={r.tracks} problems={problems} pending={session.pending} step="rights" current={track} onPick={setTrack} />
          <Button label={`Copy to all ${r.tracks.length}`} size="sm" onPress={copyToAll} />
        </div>
      )}
      <div className={s.twoUp}>
        <AiCreditsPanel t={t} patch={patchAi} />
        <RightsSeal t={t} i={track} patch={patchRights} />
      </div>
    </div>
  );
}
