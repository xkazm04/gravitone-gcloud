"use client";

// THE AI & RIGHTS EDITORS (variant "sheet"): one track's AI credits (which parts were generated; when all the audio
// was, whether the artist is a human or an AI persona) and the provenance record the take was accepted with. Both
// write the track through `patchTrack`; "Copy to all" stamps this track's two records onto every other track.
import { Button } from "@gt/ui/components/button/Button.tsx";
import { Field } from "@gt/ui/components/field/Field.tsx";
import { Seg } from "@gt/ui/components/seg/Seg.tsx";
import { Toggle } from "@gt/ui/components/toggle/Toggle.tsx";
import { AI_AUDIO, LICENCES, type AiCredits, type Release, type RightsRecord } from "@gt/domain/release";

import type { DraftEvent } from "../../../../../_release/draft.ts";
import { orNull } from "../../../../../_release/wizard/fmt.ts";
import { Cell } from "./EditRelease.tsx";
import { LICENCE_LABEL, RECORD_FIELDS } from "./words.ts";
import s from "./dialog.module.css";

type PersonaChoice = "human" | "ai" | "unstated";

interface Props {
  readonly r: Release;
  readonly i: number;
  readonly dispatch: (e: DraftEvent) => void;
}

function CopyToAll({ r, i, dispatch }: Props) {
  const t = r.tracks[i];
  if (t === undefined || r.tracks.length < 2) return null;
  return (
    <span className={s.row}>
      <Button label={`Copy to all ${r.tracks.length} tracks`} size="sm" onPress={() => r.tracks.forEach((_, j) => j !== i && dispatch({ type: "patchTrack", id: r.id, index: j, fields: { ai: t.ai, rights: t.rights } }))} />
    </span>
  );
}

export function EditAi({ r, i, dispatch }: Props) {
  const t = r.tracks[i];
  if (t === undefined) return null;
  const patchAi = (f: Partial<AiCredits>) => dispatch({ type: "patchTrack", id: r.id, index: i, fields: { ai: { ...t.ai, ...f } } });
  return (
    <div className={s.editor}>
      <div className={s.block}>
        <div className={s.choice}>
          <span className={s.k}>lyrics</span>
          <Toggle label={t.ai.lyrics ? "AI-written" : "human-written"} on={t.ai.lyrics} onToggle={(v) => patchAi({ lyrics: v })} name="lyrics generated by AI" />
        </div>
        <div className={s.choice}>
          <span className={s.k}>music</span>
          <Toggle label={t.ai.music ? "AI-composed" : "human-composed"} on={t.ai.music} onToggle={(v) => patchAi({ music: v })} name="music generated by AI" />
        </div>
        <div className={s.choice}>
          <span className={s.k}>audio</span>
          <Seg label="audio generated by AI" options={AI_AUDIO.map((a) => ({ value: a, label: a }))} value={t.ai.audio} onChange={(v) => patchAi({ audio: v, persona: v === "all" ? t.ai.persona : null })} />
        </div>
        {t.ai.audio === "all" && (
          <div className={s.choice}>
            <span className={s.k}>artist is</span>
            <Seg<PersonaChoice>
              label="the artist is a human or an AI persona"
              options={[
                { value: "human", label: "a human" },
                { value: "ai", label: "an AI persona" },
                { value: "unstated", label: "unstated" },
              ]}
              value={t.ai.persona ?? "unstated"}
              onChange={(v) => patchAi({ persona: v === "unstated" ? null : v })}
            />
          </div>
        )}
      </div>
      <CopyToAll r={r} i={i} dispatch={dispatch} />
    </div>
  );
}

export function EditRecord({ r, i, dispatch }: Props) {
  const t = r.tracks[i];
  if (t === undefined) return null;
  const patchRights = (f: Partial<RightsRecord>) => dispatch({ type: "patchTrack", id: r.id, index: i, fields: { rights: { ...t.rights, ...f } } });
  return (
    <div className={s.editor}>
      <div className={s.form}>
        {RECORD_FIELDS.map((f) => (
          <Cell key={f.key} k={f.label}>
            <Field label={f.label} value={t.rights[f.key] ?? ""} placeholder={f.example} onChange={(v) => patchRights({ [f.key]: orNull(v) })} />
          </Cell>
        ))}
      </div>
      <div className={s.choice}>
        <span className={s.k}>licence</span>
        <Seg label="licence" options={LICENCES.map((l) => ({ value: l, label: LICENCE_LABEL[l] }))} value={t.rights.licence} onChange={(v) => patchRights({ licence: v })} />
      </div>
      <CopyToAll r={r} i={i} dispatch={dispatch} />
    </div>
  );
}
