"use client";

// The AI & rights items' editors, in the dialog (prototype dock-package, round 2, variant "checklist"): DistroKid's
// AI Credits and the provenance record, one track at a time, with a copy of the track's AI & rights to every track.
import { Button } from "@gt/ui/components/button/Button.tsx";
import { Field } from "@gt/ui/components/field/Field.tsx";
import { Seg } from "@gt/ui/components/seg/Seg.tsx";
import { Toggle } from "@gt/ui/components/toggle/Toggle.tsx";
import { AI_AUDIO, LICENCES, type AiCredits, type Licence, type RightsRecord } from "@gt/domain/release";

import { orNull } from "../../../../../../_release/wizard/fmt.ts";
import { Cell } from "./details.tsx";
import { setTrack, type EditorProps } from "./types.ts";
import e from "./editors.module.css";

const LICENCE_LABEL: Readonly<Record<Licence, string>> = { commercial: "commercial", "cc-by-nc": "CC BY-NC", unknown: "unknown" };
type PersonaChoice = "human" | "ai" | "unstated";

function editTrack(p: EditorProps) {
  const t = p.r.tracks[p.track];
  const patch = setTrack(p);
  return {
    t,
    ai: (f: Partial<AiCredits>) => t !== undefined && patch({ ai: { ...t.ai, ...f } }),
    rights: (f: Partial<RightsRecord>) => t !== undefined && patch({ rights: { ...t.rights, ...f } }),
  };
}

/** Every other track takes this track's AI credits and rights record. */
export function CopyToAll(p: EditorProps) {
  const t = p.r.tracks[p.track];
  if (t === undefined || p.r.tracks.length < 2) return null;
  const copy = () => p.r.tracks.forEach((_, i) => i !== p.track && p.session.dispatch({ type: "patchTrack", id: p.r.id, index: i, fields: { ai: t.ai, rights: t.rights } }));
  return <Button label={`Copy to all ${p.r.tracks.length} tracks`} size="sm" onPress={copy} />;
}

export function AiEditor(p: EditorProps) {
  const { t, ai } = editTrack(p);
  if (t === undefined) return null;
  return (
    <div className={e.form}>
      <Cell k="lyrics">
        <Toggle label={t.ai.lyrics ? "AI-written" : "human-written"} on={t.ai.lyrics} onToggle={(v) => ai({ lyrics: v })} name="lyrics generated by AI" />
      </Cell>
      <Cell k="music">
        <Toggle label={t.ai.music ? "AI-composed" : "human-composed"} on={t.ai.music} onToggle={(v) => ai({ music: v })} name="music generated by AI" />
      </Cell>
      <Cell k="audio" wide>
        <Seg label="audio generated by AI" options={AI_AUDIO.map((a) => ({ value: a, label: a }))} value={t.ai.audio} onChange={(v) => ai({ audio: v, persona: v === "all" ? t.ai.persona : null })} />
      </Cell>
    </div>
  );
}

export function PersonaEditor(p: EditorProps) {
  const { t, ai } = editTrack(p);
  if (t === undefined) return null;
  if (t.ai.audio !== "all") {
    return (
      <Cell k="audio">
        <Seg label="audio generated by AI" options={AI_AUDIO.map((a) => ({ value: a, label: a }))} value={t.ai.audio} onChange={(v) => ai({ audio: v })} />
      </Cell>
    );
  }
  return (
    <Cell k="artist is">
      <Seg<PersonaChoice>
        label="the artist is a human or an AI persona"
        options={[
          { value: "human", label: "a human" },
          { value: "ai", label: "an AI persona" },
          { value: "unstated", label: "unstated" },
        ]}
        value={t.ai.persona ?? "unstated"}
        onChange={(v) => ai({ persona: v === "unstated" ? null : v })}
      />
    </Cell>
  );
}

export function LicenceEditor(p: EditorProps) {
  const { t, rights } = editTrack(p);
  if (t === undefined) return null;
  return (
    <Cell k="licence">
      <Seg label="licence" options={LICENCES.map((l) => ({ value: l, label: LICENCE_LABEL[l] }))} value={t.rights.licence} onChange={(v) => rights({ licence: v })} />
    </Cell>
  );
}

const TEXT = (keys: readonly (readonly [Exclude<keyof RightsRecord, "licence">, string, string?])[]) =>
  function TextFields(p: EditorProps) {
    const { t, rights } = editTrack(p);
    if (t === undefined) return null;
    return (
      <div className={e.form}>
        {keys.map(([key, k, example]) => (
          <Cell key={key} k={k} wide={keys.length === 1}>
            <Field label={k} value={t.rights[key] ?? ""} {...(example === undefined ? {} : { placeholder: example })} onChange={(v) => rights({ [key]: orNull(v) })} />
          </Cell>
        ))}
      </div>
    );
  };

export const TierEditor = TEXT([["planTier", "plan tier at generation", "Pro"]]);
export const GeneratorEditor = TEXT([
  ["vendor", "generator", "suno"],
  ["model", "model", "v5"],
]);
export const ProvenanceEditor = TEXT([
  ["generatedAt", "generated", "YYYY-MM-DD"],
  ["briefDigest", "brief digest", "sha256:…"],
  ["reference", "reference"],
]);
