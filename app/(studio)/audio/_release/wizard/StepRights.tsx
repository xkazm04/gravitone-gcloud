"use client";

// Step 3, AI & rights: per track, DistroKid's AI Credits (which parts were generated; when all the
// audio was, whether the artist is a human or an AI persona) and the provenance record the take was
// accepted with. Rights warnings are loud and stop nothing.
import { Button } from "@gt/ui/components/button/Button.tsx";
import { Chip } from "@gt/ui/components/chip/Chip.tsx";
import { Field } from "@gt/ui/components/field/Field.tsx";
import { CapsHeading } from "@gt/ui/components/heading/CapsHeading.tsx";
import { Seg } from "@gt/ui/components/seg/Seg.tsx";
import { Toggle } from "@gt/ui/components/toggle/Toggle.tsx";
import { AI_AUDIO, LICENCES, type AiCredits, type Licence, type RightsRecord } from "@gt/domain/release";
import { rightsWarnings } from "@gt/domain/release.problems";

import { orNull } from "./fmt.ts";
import { Problems } from "./Problems.tsx";
import { problemsOnTrack, type StepProps } from "./steps.ts";
import { TrackStrip } from "./TrackStrip.tsx";
import s from "./step.module.css";

const LICENCE_LABEL: Readonly<Record<Licence, string>> = { commercial: "commercial", "cc-by-nc": "CC BY-NC", unknown: "unknown" };
type PersonaChoice = "human" | "ai" | "unstated";

const RECORD_FIELDS: readonly { readonly key: Exclude<keyof RightsRecord, "licence">; readonly label: string; readonly example?: string }[] = [
  { key: "vendor", label: "generator", example: "suno" },
  { key: "model", label: "model", example: "v5" },
  { key: "planTier", label: "plan tier at generation", example: "Pro" },
  { key: "generatedAt", label: "generated", example: "YYYY-MM-DD" },
  { key: "briefDigest", label: "brief digest", example: "sha256:…" },
  { key: "reference", label: "reference" },
];

export function StepRights(props: StepProps) {
  const { release: r, problems, dispatch, track, setTrack } = props;
  const t = r.tracks[track];
  if (t === undefined) return <Chip label="no tracks" ghost />;
  const patchAi = (f: Partial<AiCredits>) => dispatch({ type: "patchTrack", id: r.id, index: track, fields: { ai: { ...t.ai, ...f } } });
  const patchRights = (f: Partial<RightsRecord>) => dispatch({ type: "patchTrack", id: r.id, index: track, fields: { rights: { ...t.rights, ...f } } });
  const copyToAll = () => r.tracks.forEach((_, i) => i !== track && dispatch({ type: "patchTrack", id: r.id, index: i, fields: { ai: t.ai, rights: t.rights } }));
  const warnings = rightsWarnings(t.rights);
  const persona: PersonaChoice = t.ai.persona ?? "unstated";
  return (
    <div className={s.stack}>
      <div className={s.toolbar}>
        <TrackStrip tracks={r.tracks} problems={problems} step="rights" current={track} onPick={setTrack} />
        {r.tracks.length > 1 && <Button label={`Copy to all ${r.tracks.length} tracks`} size="sm" onPress={copyToAll} />}
      </div>
      <Problems problems={problemsOnTrack(problems, "rights", track).filter((p) => p.code === "persona-unstated")} label="AI credit problems" />
      <div className={s.twoCol}>
        <section className={s.section} aria-label="AI credits">
          <CapsHeading text="AI credits" variant="section" />
          <div className={s.choiceRows}>
            <div className={s.choice}>
              <span className={s.k}>lyrics</span>
              <Toggle label={t.ai.lyrics ? "AI-written" : "human-written"} on={t.ai.lyrics} onToggle={(v) => patchAi({ lyrics: v })} name="lyrics generated by AI" />
            </div>
            <div className={s.choice}>
              <span className={s.k}>music</span>
              <Toggle label={t.ai.music ? "AI-composed" : "human-composed"} on={t.ai.music} onToggle={(v) => patchAi({ music: v })} name="music generated by AI" />
            </div>
            <div className={s.choice}>
              <span className={s.k}>audio</span>
              <Seg label="audio generated by AI" options={AI_AUDIO.map((a) => ({ value: a, label: a }))} value={t.ai.audio} onChange={(v) => patchAi({ audio: v, persona: v === "all" ? t.ai.persona : null })} />
            </div>
            {t.ai.audio === "all" && (
              <div className={s.choice} data-need={t.ai.persona === null ? "" : undefined}>
                <span className={s.k}>artist is</span>
                <Seg<PersonaChoice>
                  label="the artist is a human or an AI persona"
                  options={[
                    { value: "human", label: "a human" },
                    { value: "ai", label: "an AI persona" },
                    { value: "unstated", label: "unstated" },
                  ]}
                  value={persona}
                  onChange={(v) => patchAi({ persona: v === "unstated" ? null : v })}
                />
              </div>
            )}
          </div>
        </section>
        <section className={s.section} aria-label="rights record">
          <CapsHeading text="Rights record" variant="section" />
          {warnings.length > 0 && <Problems problems={problemsOnTrack(problems, "rights", track).filter((p) => p.code !== "persona-unstated")} label="rights warnings" />}
          <div className={s.form} data-cols="2">
            {RECORD_FIELDS.map((f) => (
              <label key={f.key} className={s.cell}>
                <span className={s.k}>{f.label}</span>
                <Field label={f.label} value={t.rights[f.key] ?? ""} placeholder={f.example} onChange={(v) => patchRights({ [f.key]: orNull(v) })} />
              </label>
            ))}
          </div>
          <div className={s.choice}>
            <span className={s.k}>licence</span>
            <Seg label="licence" options={LICENCES.map((l) => ({ value: l, label: LICENCE_LABEL[l] }))} value={t.rights.licence} onChange={(v) => patchRights({ licence: v })} />
          </div>
          {warnings.length === 0 && <Chip label="record complete" tone="emerald" dot />}
        </section>
      </div>
    </div>
  );
}
